"""Сторож ворот: хуки коуча работают на своём мозге и молчат в чужих проектах.

**Почему тест, а не внимательность.** Ворота хуков опознают свой мозг по полю `имя`
в метке `.loreground` (`hooks/_gate.py`). Опознание молчаливое по устройству: не наш
проект — сторож уходит тихо. У молчания есть цена, и она вся здесь: испорти поле `имя`
в метке мозга — и оба сторожа умрут, не сказав ни слова, а их молчание читается как
«всё в порядке». Это ровно тот класс беды, против которого хуки и заведены, поэтому
поле стережёт прибор.

**Почему это всплыло.** 13.08.2026 выяснилось, что прежние ворота («есть файл
`.loreground` — работаю») пускали наших сторожей в ЧУЖИЕ проекты, собранные настоящим
Loreground: плагины ставятся на машину целиком, и реплика 0.15.1 просыпалась рядом со
свежим комплектом, выдавая устаревшие вердикты за находки. Разбор — в `_gate.py`.
"""

from __future__ import annotations

import sys
from pathlib import Path

ПЛАГИН = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ПЛАГИН / "hooks"))

from _gate import BRAND, свой_мозг  # noqa: E402

МЕТКА = ПЛАГИН / "brain-template" / ".loreground"


def test_у_шаблона_мозга_есть_метка():
    assert МЕТКА.is_file(), (
        "В шаблоне мозга нет метки .loreground. Без неё оба хука молчат "
        "на собранном мозге, и молчание читается как «проверено, чисто»."
    )


def test_метка_шаблона_называет_наш_бренд():
    строки = МЕТКА.read_text(encoding="utf-8").splitlines()
    имена = [s.split(":", 1)[1].strip() for s in строки if s.strip().startswith("имя:")]
    assert имена == [BRAND], (
        f"Поле «имя» в метке шаблона мозга должно быть ровно «{BRAND}», "
        f"а стоит {имена!r}. По нему хуки узнают свой мозг: разойдётся — "
        "сторожа выключатся молча."
    )


def test_ворота_пускают_свой_мозг():
    assert свой_мозг(МЕТКА.parent) is True


def test_ворота_молчат_в_чужом_проекте(tmp_path):
    """Метка есть, но собрана другим агентом — не наше дело."""
    (tmp_path / ".loreground").write_text(
        "собран_на_версии: 0.35.0\nсобран: 2026-08-13\nимя: другой-агент\nрежим: указатель\n",
        encoding="utf-8",
    )
    assert свой_мозг(tmp_path) is False


def test_ворота_молчат_без_имени(tmp_path):
    """Метка без поля «имя» — не опознана, значит не наша (сомнение в пользу молчания)."""
    (tmp_path / ".loreground").write_text(
        "собран_на_версии: 0.15.1\nсобран: 2026-08-02\n", encoding="utf-8"
    )
    assert свой_мозг(tmp_path) is False


def test_ворота_молчат_без_метки(tmp_path):
    assert свой_мозг(tmp_path) is False


def test_папка_меткой_не_считается(tmp_path):
    """`mkdir .loreground` не должен включать сторожей."""
    (tmp_path / ".loreground").mkdir()
    assert свой_мозг(tmp_path) is False


def test_имя_читается_с_комментарием_и_в_другом_регистре(tmp_path):
    (tmp_path / ".loreground").write_text(
        f"имя: {BRAND.upper()}  # мозг на сервере\n", encoding="utf-8"
    )
    assert свой_мозг(tmp_path) is True
