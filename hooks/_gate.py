#!/usr/bin/env python3
"""Ворота хуков коуча: свой мозг или чужой проект.

**Зачем понадобилось.** Хуки этого плагина — реплика Loreground 0.15.1, и ворота
у них были один в один комплектные: «есть в папке файл `.loreground` — работаю».
Для комплекта это верно: он один на машине, и всякая метка — его метка. Для реплики
неверно, и разница вылезла боем 13.08.2026.

Плагины ставятся не в проект, а на машину целиком: включены все и везде. Значит
в любом проекте, собранном НАСТОЯЩИМ Loreground, на одной машине с нами
просыпались ДВА комплекта одинаковых сторожей — свежий комплектный и наша реплика,
застывшая на 0.15.1. Реплика честно докладывала правду двухнедельной давности:
«команда `lore-validate` не найдена» (починку 0.35.0 она не знает) и «кодекс
устарел, источник версии 1» (сверялась со своим старым `codex.md`). Оба сообщения
ложные, оба выглядели как находка в чужой базе, и владелец того проекта потратил
вечер на поиск поломки, которой нет.

`hooks/README.md` до этого дня утверждал обратное: «метка есть только в мозге —
значит вне мозга хуки не подают голоса». Утверждение было проверкой не подкреплено
и оказалось неверным: метку кладёт себе каждый агент, собранный по стандарту.

**Что здесь решается.** Ворота сужаются с «любая метка» до «метка НАШЕЙ сборки».
Поле для этого в метке уже есть — `имя`, и в обеих живых метках (шаблон мозга
и мозг на сервере, проверено 13.08.2026) там стоит `gtd-coach`.

**Сомнение решается в пользу молчания, и это осознанный размен.** Метка без поля
`имя`, с чужим именем, нечитаемая — всё это «не наш мозг», сторож уходит тихо.
Обратный выбор («не понял — поработаю») возвращал бы ровно ту беду, ради которой
файл заведён: ложную тревогу в чужом проекте. Цена размена — свой мозг с испорченной
меткой останется без сторожей молча; поэтому метку шаблона стережёт отдельный тест
(`tests/test_метка_мозга.py`), а не наша внимательность.
"""
import os
import re

MARKER = ".loreground"
BRAND = "gtd-coach"
# Поле метки читается тем же способом, что и в комплекте (`version-drift.py`):
# построчно регуляркой, а не разбором YAML. Причина простая — PyYAML может не стоять,
# а ворота обязаны отработать раньше всех остальных проверок.
NAME_RE = re.compile(r"^[ \t]*имя[ \t]*:[ \t]*(.+?)[ \t]*$", re.M)


def свой_мозг(project):
    """Собран ли этот проект коучем. Всё непонятное — «нет», сторож молчит."""
    try:
        with open(os.path.join(project, MARKER), encoding="utf-8") as handle:
            текст = handle.read()
    except (OSError, UnicodeDecodeError, IsADirectoryError):
        # Метки нет, она нечитаема или это папка с таким именем. Папка меткой не
        # считается намеренно: `mkdir .loreground` не должен включать сторожей.
        return False

    найдено = NAME_RE.search(текст)
    if найдено is None:
        return False

    имя = найдено.group(1)
    # Комментарий после значения регулярка захватывает, а именем он не является:
    # `имя: gtd-coach  # мозг на сервере` — это то же имя.
    имя = имя.split("#", 1)[0].strip().strip("\"'").strip()
    # Регистр не различается: метку пишет человек руками, и `GTD-Coach` — та же сборка.
    return имя.casefold() == BRAND.casefold()
